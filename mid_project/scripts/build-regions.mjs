// Builds src/data/regions.ts (시군구 5-digit codes for the 실거래가 API LAWD_CD) from the official CSV.
// Source: 공공데이터포털 "국토교통부_전국 법정동" (https://www.data.go.kr/data/15063424/fileData.do).
// The CSV is not committed (size); download it and run:
//   node scripts/build-regions.mjs <path-to-csv> <basis-date YYYY-MM-DD>
import { readFileSync, writeFileSync } from "node:fs";

const [csvPath, basisDate] = process.argv.slice(2);
if (!csvPath || !/^\d{4}-\d{2}-\d{2}$/.test(basisDate ?? "")) {
  console.error("usage: node scripts/build-regions.mjs <csv> <YYYY-MM-DD>");
  process.exit(1);
}

const lines = readFileSync(csvPath, "utf8").replace(/^﻿/, "").trim().split(/\r?\n/);
const header = lines[0].split(",");
const col = (name) => header.indexOf(name);
const [iCode, iSido, iSgg, iUmd] = ["법정동코드", "시도명", "시군구명", "읍면동명"].map(col);

// 시군구 rows: code like SSGGG00000 with a non-zero 시군구 part and no 읍면동.
const sgg = lines
  .slice(1)
  .map((l) => l.split(","))
  .filter((r) => r[iCode].endsWith("00000") && r[iCode].slice(2, 5) !== "000" && r[iUmd] === "")
  .map((r) => ({ code: r[iCode].slice(0, 5), sido: r[iSido], sigungu: r[iSgg] }));

// A 시 that has 구 (e.g. 41110 수원시 -> 41111 수원시장안구) returns no trades; keep only its 구.
const isParentCity = (p) =>
  p.code.endsWith("0") &&
  sgg.some((c) => c.code !== p.code && c.code.slice(0, 4) === p.code.slice(0, 4) && c.sigungu.startsWith(p.sigungu));
const regions = sgg.filter((r) => !isParentCity(r));

const body = `// Generated by scripts/build-regions.mjs. Do not edit by hand.
// Source: 공공데이터포털 "국토교통부_전국 법정동" (https://www.data.go.kr/data/15063424/fileData.do), basis date ${basisDate}.
// code = 법정동코드 앞 5자리 (실거래가 API LAWD_CD).

export type Region = { code: string; sido: string; sigungu: string };

export const REGIONS_BASIS_DATE = "${basisDate}";

export const REGIONS: Region[] = [
${regions.map((r) => `  { code: "${r.code}", sido: "${r.sido}", sigungu: "${r.sigungu}" },`).join("\n")}
];
`;
writeFileSync(new URL("../src/data/regions.ts", import.meta.url), body);
console.log(`regions: ${regions.length} (excluded parent cities: ${sgg.length - regions.length})`);
